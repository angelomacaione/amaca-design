def read(p):
    return (ROOT / p).read_bytes()


def stamp():
    m = re.search(r"^updated:\s*(\d{4})-(\d{2})-(\d{2})", (ROOT / "DESIGN.md").read_text(), re.M)
    return (int(m.group(1)), int(m.group(2)), int(m.group(3)), 0, 0, 0)


def text_of(step):
    t = re.sub(r"</?(b|i)>", "**", step)
    t = re.sub(r"</?code>", "`", t)
    return html.unescape(re.sub(r"<[^>]+>", "", t))


def members(b):
    """[(archive path, bytes)] in the order the README lists them."""
    out = []
    skill = zipfile.ZipFile(ROOT / SKILL)
    for arc, src in b["files"].items():
        if src.startswith("skill:"):
            pre = src[6:]
            for n in sorted(skill.namelist()):
                if n.startswith(pre) and not n.endswith("/"):
                    out.append((arc + n[len(pre):], skill.read(n)))
        else:
            out.append((arc, read(src)))
    return out


def readme(b, files):
    lines = [f"# Amaca — {b['title']}", "", b["desc"], "", "## How to install", ""]
    lines += [f"{i}. {text_of(s)}" for i, s in enumerate(b["steps"], 1)]
    lines += ["", "## What's inside", ""] + [f"- `{a}`" for a, _ in files] + ["- `README.md` (this file)", "",
              "On conflict, DESIGN.md wins. — Amaca · MIT · https://amaca.design", ""]
    return "\n".join(lines).encode()


def build_zip(b):
    files = members(b)
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for arc, data in [("README.md", readme(b, files))] + files:
            zi = zipfile.ZipInfo(arc, date_time=stamp())
            zi.external_attr = 0o644 << 16
            zi.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(zi, data)
    return buf.getvalue()


def inside(b):
    """[(path, bytes)] as the card lists it: README first, then the files."""
    if b.get("inside") == "npm":
        sys.path.insert(0, str(ROOT / "release"))
        import npm
        return [(k, len(read(v))) for k, v in sorted(npm.FILES.items())] + [("package.json", None), ("README.md", None)]
    if b.get("inside") == "shadcn":
        return [("styles/amaca/<name>.css", None), ("components/amaca/<name>.html", None), ("the contract, in meta.amaca", None)]
    z = zipfile.ZipFile(io.BytesIO(read("downloads/zips/" + b["zip"])))
    out, folded = [], {}
    for i in z.infolist():
        if i.filename.endswith("/"):
            continue
        m = re.match(r"(.*?skills/[^/]+/)", i.filename)   # a skill folder reads as one line: its files travel together
        if m:
            k = m.group(1)
            if k not in folded:
                folded[k] = [0, 0]
                out.append((k, None))
            folded[k][0] += 1
            folded[k][1] += i.file_size
        else:
            out.append((i.filename, i.file_size))
    return [(f"{p} · {folded[p][0]} files", folded[p][1]) if p in folded else (p, n) for p, n in out]


def size(n):
    if n is None:
        return ""
    return f"{n / 1000:.0f} KB" if n >= 1000 else f"{n} B"


EYEBROW = "dl-eyebrow"


