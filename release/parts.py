#!/usr/bin/env python3
"""The parts of every component, for the short rules files, generated from the shadcn registry in r/.

v6.0.0: AGENTS.md, CLAUDE.md, AI-INSTRUCTIONS.md and llms-full.txt named the components and never their parts,
so an agent reading only them invented .card-body and .card-head, and wrote no Badge variant at all (0 of 12 runs
in the 2026-10 benchmark). One line per component: its root class, its parts, its variants by axis.

    python3 release/parts.py           rewrite the block in every file
    python3 release/parts.py --check   exit 1 if a block differs from r/
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = ["downloads/AGENTS.md", "downloads/CLAUDE.md", "downloads/AI-INSTRUCTIONS.md", "llms-full.txt"]
START, END = "<!-- parts:start (generated by release/parts.py) -->", "<!-- parts:end -->"
ANCHOR = re.compile(r"^## Components[^\n]*\n(?:(?!^## ).*\n)*", re.M)


def block():
    reg = json.loads((ROOT / "r" / "registry.json").read_text())
    lines = [START, "**Parts and variants** (one line per component; build only these, never invent a part):"]
    for it in reg["items"]:
        if it["name"] == "amaca-tokens":
            continue
        meta = json.loads((ROOT / "r" / f"{it['name']}.json").read_text())["meta"]["amaca"]
        named = {v.lstrip(".") for ax in meta.get("variants", []) for v in ax["values"]}
        classes = [c for c in meta.get("classes", []) if not c.startswith(("is-", "has-"))]   # states are not parts
        root = (next((c for c in classes if c == it["name"] or it["name"].startswith(c)), None)
                or next((c for c in classes if c.endswith("-wrap")), None)
                or min(classes, key=len, default=""))
        parts = [c for c in classes if c != root and c not in named]
        axes = "; ".join(f"{ax['axis']}: " + " | ".join(ax["values"]) for ax in meta.get("variants", []))
        line = f"- **{it['title']}** `.{root}`" if root else f"- **{it['title']}**"
        if parts:
            line += " · parts " + " ".join(f"`.{p}`" for p in parts)
        if axes:
            line += " · " + axes
        lines.append(line)
    lines.append(END)
    return "\n".join(lines) + "\n"


def apply(text, b):
    if START in text:
        return re.sub(re.escape(START) + r".*?" + re.escape(END) + r"\n", lambda m: b, text, flags=re.S)
    m = ANCHOR.search(text)
    if not m:
        raise SystemExit("no '## Components' section to put the parts under")
    return text[:m.end()] + "\n" + b + "\n" + text[m.end():]


def main(argv):
    b, stale = block(), []
    for f in FILES:
        p = ROOT / f
        old = p.read_text()
        new = apply(old, b)
        if new != old:
            stale.append(f)
            if "--check" not in argv:
                p.write_text(new)
    if "--check" in argv:
        for f in stale:
            print(f"{f}: the parts block differs from r/")
        return 1 if stale else 0
    print(f"wrote the parts block to {len(stale)} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
